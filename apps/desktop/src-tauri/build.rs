fn main() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        println!("cargo:rerun-if-changed=../apple/MacPermissions.mm");
        println!("cargo:rerun-if-changed=../apple/SelectedNote.mm");
        println!("cargo:rerun-if-changed=../apple/AppleVoiceMemos.mm");
        println!("cargo:rerun-if-changed=../apple/AppleResourceAttachment.h");
        println!("cargo:rustc-link-lib=framework=ApplicationServices");
        println!("cargo:rustc-link-lib=framework=AVFoundation");
        println!("cargo:rustc-link-lib=framework=CoreServices");
        println!("cargo:rustc-link-lib=framework=ServiceManagement");
        println!("cargo:rustc-link-lib=framework=UniformTypeIdentifiers");
        println!("cargo:rustc-link-lib=sqlite3");
        cc::Build::new()
            .cpp(true)
            .flag("-fobjc-arc")
            .file("../apple/MacPermissions.mm")
            .file("../apple/SelectedNote.mm")
            .file("../apple/AppleVoiceMemos.mm")
            .compile("yonder_macos");
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("ios") {
        println!("cargo:rerun-if-changed=../apple/DeviceDownload.mm");
        cc::Build::new()
            .cpp(true)
            .flag("-fobjc-arc")
            .file("../apple/DeviceDownload.mm")
            .compile("yonder_apple_device_download");
    }
    if matches!(
        std::env::var("CARGO_CFG_TARGET_OS").as_deref(),
        Ok("ios" | "macos")
    ) {
        println!("cargo:rerun-if-changed=../apple/Notifications.mm");
        println!("cargo:rerun-if-changed=../apple/DeviceName.mm");
        println!("cargo:rerun-if-changed=../apple/AppleCalendar.mm");
        println!("cargo:rerun-if-changed=../apple/ApplePhotos.mm");
        println!("cargo:rerun-if-changed=../apple/AppleResourceBridge.h");
        println!("cargo:rustc-link-lib=framework=EventKit");
        println!("cargo:rustc-link-lib=framework=Photos");
        println!("cargo:rustc-link-lib=framework=Vision");
        println!("cargo:rustc-link-lib=framework=UserNotifications");
        if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
            println!("cargo:rustc-link-lib=framework=SystemConfiguration");
        }
        cc::Build::new()
            .cpp(true)
            .flag("-fobjc-arc")
            .file("../apple/Notifications.mm")
            .file("../apple/DeviceName.mm")
            .file("../apple/AppleCalendar.mm")
            .file("../apple/ApplePhotos.mm")
            .compile("yonder_apple");
    }
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .plugin(
                "android-update",
                tauri_build::InlinedPlugin::new()
                    .commands(&["latest", "versionCode", "downloadAndInstall"])
                    .default_permission(tauri_build::DefaultPermissionRule::AllowAllCommands),
            )
            .plugin(
                "yonder-mac-permissions",
                tauri_build::InlinedPlugin::new()
                    .commands(&[
                        "permission_status",
                        "open_settings",
                        "request_accessibility",
                        "request_microphone",
                        "login_item_status",
                        "set_login_item",
                    ])
                    .default_permission(tauri_build::DefaultPermissionRule::AllowAllCommands),
            )
            .plugin(
                "yonder-apple-resources",
                tauri_build::InlinedPlugin::new()
                    .commands(&[
                        "statuses",
                        "request_permission",
                        "open_settings",
                        "activate",
                        "reset",
                        "authorize",
                        "revoke",
                        "ready",
                        "execute",
                        "execute_attachment",
                        "cancel",
                    ])
                    .default_permission(tauri_build::DefaultPermissionRule::AllowAllCommands),
            )
            .plugin(
                "yonder-device-info",
                tauri_build::InlinedPlugin::new()
                    .commands(&["system_name"])
                    .default_permission(tauri_build::DefaultPermissionRule::AllowAllCommands),
            )
            .plugin(
                "yonder-device-download",
                tauri_build::InlinedPlugin::new().commands(&["open", "share", "copy"]),
            )
            .plugin(
                "yonder-notifications",
                tauri_build::InlinedPlugin::new()
                    .commands(&[
                        "request_permission",
                        "permission_status",
                        "push_registration",
                        "open_settings",
                        "take_open",
                        "show_desktop",
                        "registerListener",
                        "removeListener",
                    ])
                    .default_permission(tauri_build::DefaultPermissionRule::AllowAllCommands),
            ),
    )
    .expect("failed to run tauri-build")
}
